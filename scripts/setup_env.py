#!/usr/bin/env python3
"""Create services/*/.env from .env.example with fresh secrets, consistent across the services.

    python scripts/setup_env.py                      # local run (http://localhost:3000 / :3001)
    python scripts/setup_env.py --domain platform.example.com --mail-domain mail.example.com   # a VPS behind HTTPS

With --domain the script also prepares HTTPS through Caddy (the `caddy` service of docker-compose.yml):
  .env (repository root)   COMPOSE_PROFILES=https and fresh database passwords (only when the file is created)
  deploy/Caddyfile         the domains → admin-web / mail-web; certificates are issued and renewed by Caddy
Running it again with other domains updates only the addresses in services/*/.env, never their secrets.

Secrets shared by two services are generated once and written to both:
  llm ADMIN_API_TOKEN  = admin RAG_API_TOKEN       (admin → llm)
  admin BOOTSTRAP_INTEGRATIONS key = mail PLATFORM_API_KEY   (mail → admin /v1)
Existing .env files are left untouched (use --force to overwrite). Model keys (OPENROUTER_API_KEY) are not
generated: put them into services/llm/.env yourself.
"""

from __future__ import annotations

import argparse
import base64
import re
import secrets
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def token(n: int = 32) -> str:
    return secrets.token_urlsafe(n)


def fernet_key() -> str:
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()


def fill(example: Path, values: dict[str, str]) -> str:
    out = []
    for line in example.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^(#\s*)?([A-Z0-9_]+)=", line)
        if m and m.group(2) in values:
            line = f"{m.group(2)}={values[m.group(2)]}"
        out.append(line)
    return "\n".join(out) + "\n"


def update(env: Path, values: dict[str, str]) -> None:
    """Set the given keys in an existing .env, keep every other line (and every secret) as it is."""
    lines, seen = env.read_text(encoding="utf-8").splitlines(), set()
    for i, line in enumerate(lines):
        m = re.match(r"^(#\s*)?([A-Z0-9_]+)=", line)
        if m and m.group(2) in values and m.group(2) not in seen:
            lines[i] = f"{m.group(2)}={values[m.group(2)]}"
            seen.add(m.group(2))
    lines += [f"{k}={v}" for k, v in values.items() if k not in seen]
    env.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_env(env: Path) -> dict[str, str]:
    if not env.exists():
        return {}
    pairs = (line.split("=", 1) for line in env.read_text(encoding="utf-8").splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs if not k.lstrip().startswith("#")}


def caddyfile(domain: str, mail_domain: str | None, email: str | None) -> str:
    out = ["# Generated by scripts/setup_env.py — run it again to change the domains.", ""]
    if email:
        out += ["{", f"\temail {email}", "}", ""]
    out += [f"{domain} {{", "\tencode zstd gzip", "\treverse_proxy admin-web:80", "}", ""]
    if mail_domain:
        out += [f"{mail_domain} {{", "\tencode zstd gzip", "\treverse_proxy mail-web:80", "}", ""]
    return "\n".join(out)


def setup_https(domain: str, mail_domain: str | None, email: str | None) -> None:
    root_env = ROOT / ".env"
    current = read_env(root_env)
    profiles = [p for p in current.get("COMPOSE_PROFILES", "").split(",") if p]
    values = {"COMPOSE_PROFILES": ",".join(dict.fromkeys([*profiles, "https"]))}
    if not root_env.exists():  # Postgres takes a password only when its volume is created: never change it later
        values |= {"ADMIN_DB_PASSWORD": token(24), "MAIL_DB_PASSWORD": token(24), "RAG_DB_PASSWORD": token(24)}
        root_env.write_text("# docker compose reads this file by itself (scripts/setup_env.py)\n", encoding="utf-8")
    update(root_env, values)
    root_env.chmod(0o600)
    print(f"wrote {root_env.relative_to(ROOT)}")
    cf = ROOT / "deploy/Caddyfile"
    cf.parent.mkdir(exist_ok=True)
    cf.write_text(caddyfile(domain, mail_domain, email), encoding="utf-8")
    print(f"wrote {cf.relative_to(ROOT)}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--domain", help="public domain of the admin site and API (HTTPS)")
    ap.add_argument("--mail-domain", help="public domain of the mail demo (HTTPS); without it the demo is not public")
    ap.add_argument("--email", help="e-mail for Let's Encrypt notices (optional)")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    if args.mail_domain and not args.domain:
        ap.error("--mail-domain needs --domain")

    admin_url = f"https://{args.domain}" if args.domain else "http://localhost:3001"
    rag_token, integration_key = token(), "ik_mail-demo_" + token()
    plan = {
        ROOT / "services/llm": {
            "ADMIN_API_TOKEN": rag_token, "DOC_LINK_SECRET": token(), "PUBLIC_BASE_URL": f"{admin_url}/v1/public/rag",
        },
        ROOT / "services/admin/backend": {
            "SECRET_KEY": token(48), "RAG_API_TOKEN": rag_token, "PANEL_PUBLIC_URL": admin_url, "API_PUBLIC_URL": admin_url,
            "COOKIE_SECURE": "true" if args.domain else "false",
            "BOOTSTRAP_INTEGRATIONS": f"mail-demo:Почта (демо):{integration_key}",
        },
        ROOT / "services/mail/backend": {
            "SECRET_KEY": token(48), "ENCRYPTION_KEY": fernet_key(), "PLATFORM_API_KEY": integration_key,
        },
    }
    addresses = {  # keys that depend only on the domain: updated in place when the .env already exists
        ROOT / "services/llm": ["PUBLIC_BASE_URL"],
        ROOT / "services/admin/backend": ["PANEL_PUBLIC_URL", "API_PUBLIC_URL", "COOKIE_SECURE"],
    }
    for folder, values in plan.items():
        env = folder / ".env"
        if env.exists() and not args.force:
            keys = addresses.get(folder, []) if args.domain else []
            if keys:
                update(env, {k: values[k] for k in keys})
                print(f"updated addresses in {env.relative_to(ROOT)} (secrets kept)")
            else:
                print(f"skip {env.relative_to(ROOT)} (exists; --force to overwrite)")
            continue
        env.write_text(fill(folder / ".env.example", values), encoding="utf-8")
        env.chmod(0o600)
        print(f"wrote {env.relative_to(ROOT)}")
    if args.domain:
        setup_https(args.domain, args.mail_domain, args.email)
    print("\nNext: put OPENROUTER_API_KEY into services/llm/.env, then  docker compose up -d --build")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
